// Writes dist/emoji-data.js, the emoji the tab emoji picker offers
// (dist/emoji.html), from Unicode's emoji list and CLDR's English keywords.
// Capped at Emoji 15.0, which Windows 11 and macOS 11 and later can draw.
// Skin tone variants are left out
//
//   npm run emoji-data

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const VERSION = "15.0";
const TEST = `https://unicode.org/Public/emoji/${VERSION}/emoji-test.txt`;
const KEYWORDS = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations/en/annotations.json";

const get = async (url) => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response;
};
const [test, keywords] = await Promise.all([
  get(TEST).then((r) => r.text()),
  get(KEYWORDS).then((r) => r.json()).then((json) => json.annotations.annotations),
]);

// Smileys and people share a section, like most pickers
const GROUPS = {
  "Smileys & Emotion": "Smileys & People",
  "People & Body": "Smileys & People",
  "Animals & Nature": "Animals & Nature",
  "Food & Drink": "Food & Drink",
  "Travel & Places": "Travel & Places",
  "Activities": "Activities",
  "Objects": "Objects",
  "Symbols": "Symbols",
  "Flags": "Flags",
};
const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;

const sections = new Map();
let group = null;
for (const line of test.split("\n")) {
  const heading = /^# group: (.+)/.exec(line);
  if (heading) {
    group = GROUPS[heading[1].trim()] ?? null;
    continue;
  }
  const entry = /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/.exec(line);
  if (!entry || !group) continue;
  const [, emoji, name] = entry;
  if (SKIN_TONE.test(emoji)) continue;
  const words = new Set(name.toLowerCase().split(/[\s:,]+/));
  const extra = (keywords[emoji] ?? keywords[emoji.replace(/\uFE0F/g, "")])?.default ?? [];
  const tags = extra.map((word) => word.toLowerCase()).filter((word) => !words.has(word));
  if (!sections.has(group)) sections.set(group, []);
  sections.get(group).push(`${emoji}|${name}${tags.length ? `|${tags.join(" ")}` : ""}`);
}

// One string per section, `emoji|name|keywords` entries split by newlines,
// keeps the file small and quick to parse
const body = [...sections].map(([name, entries]) => `  [${JSON.stringify(name)}, ${JSON.stringify(entries.join("\n"))}],`).join("\n");
const out = `// Generated by scripts/emoji-data.mjs from Unicode Emoji ${VERSION} and CLDR. Don't edit
// Copyright © 1991-2025 Unicode, Inc. Unicode License v3: https://www.unicode.org/license.txt
// [section, "emoji|name|keywords" lines]
const LIGMA_EMOJI = [
${body}
];
`;
writeFileSync(join(root, "dist", "emoji-data.js"), out);
const count = [...sections.values()].reduce((sum, entries) => sum + entries.length, 0);
console.log(`dist/emoji-data.js: ${count} emoji, ${(out.length / 1024).toFixed(0)} KB`);
